# Шаблон пути к странице события. Свой формат у каждой площадки движка:
# melbet.ru открывает матч по внутреннему маршруту приложения
# («/ru/sport/event-details/<чемпионат>-<событие>-<страна>-<спорт>-0-<лайв>
# -0-<команды>»), международные зеркала — по SEO-адресу
# («/ru/line/<спорт>/<чемпионат>-<слаг>/<событие>-<команды>»). Какой из них
# ваш и из каких полей фида он собирается, подбирает
# «python -m app.diagnose_melbet --links»: он строит варианты на живых
# событиях и проверяет их на сайте. Плейсхолдеры перечислены там же.
MELBET_EVENT_URL = os.getenv("MELBET_EVENT_URL", "").strip()
# Языка, «страны» и партнёра в настройках нет намеренно: фид принимает
# ТОЛЬКО те строки запроса, которые шлёт сам сайт, — с лишним параметром
# (например, с lng при любом значении) он отвечает 406 на весь запрос. Без
# lng фид и так отвечает по-русски, а по русским названиям команд события и
# сшиваются с остальными БК РФ.
# Сколько событий просить в одном запросе линии. Фид принимает только
# значения, КРАТНЫЕ 5, и всё равно не отдаёт больше 50 за раз, сколько ни
# проси, — поэтому 50. Линия целиком собирается не количеством, а
# разбивкой на чемпионаты (MELBET_CHAMPS).
MELBET_SPORT_COUNT = int(os.getenv("MELBET_SPORT_COUNT", "50"))
MELBET_LIVE_COUNT = int(os.getenv("MELBET_LIVE_COUNT", "50"))
# Сколько видов спорта опрашивать параллельно.
MELBET_SPORT_WORKERS = int(os.getenv("MELBET_SPORT_WORKERS", "6"))
# Собирать линию по ЧЕМПИОНАТАМ, а не по видам спорта. Запрос «весь вид
# спорта» упирается в те же 50 событий, то есть отдаёт только верхушку
# (по футболу это 50 матчей из ~2700). По чемпионатам линия приходит
# целиком: сначала GetChampsZip на каждый вид спорта, потом Get1x2_VZip на
# каждый чемпионат (около 900 запросов на всю линию, ~10 с при 8 потоках).
# 0 — быстрый режим «только верхушка каждого вида спорта».
MELBET_CHAMPS = os.getenv("MELBET_CHAMPS", "1") not in ("0", "false", "no")
MELBET_CHAMP_WORKERS = int(os.getenv("MELBET_CHAMP_WORKERS", "8"))
# Забирать ПОЛНУЮ роспись события (отдельный запрос GetGameZip): лестницы
# тоталов и фор целиком, индивидуальные тоталы обеих команд.
# 0 — только рынки из снимка линии (их тоже немало: 1X2, по 6 линий
# тотала и форы, инд. тоталы, «обе забьют»).
MELBET_FULL_MARKETS = os.getenv("MELBET_FULL_MARKETS", "1") not in (
    "0", "false", "no")
MELBET_FULL_MARKETS_WORKERS = int(
    os.getenv("MELBET_FULL_MARKETS_WORKERS", "12"))
# Сколько запросов росписи максимум за один обход. Роспись — это запрос НА
# КАЖДОЕ событие, а их в линии ~7500: обойти все за отведённое время всё
# равно не выйдет, поэтому роспись берётся у событий, которые начнутся
# раньше всех (по ним и ставят), а остальные идут с рынками из снимка.
MELBET_FULL_MARKETS_MAX = int(os.getenv("MELBET_FULL_MARKETS_MAX", "1200"))
# Сколько подигр (тайм, период, «угловые», «жёлтые карточки») забирать у
# одного события. Рынки подигры лежат за отдельным запросом — своим
# GetGameZip, — поэтому берём только первые: периоды идут раньше
# предметных подигр. 0 — не брать подигры вовсе.
MELBET_SUBGAMES = int(os.getenv("MELBET_SUBGAMES", "4"))
# Сколько секунд максимум тратить на сбор всей линии за один обход.
MELBET_FEED_TIMEOUT = float(os.getenv("MELBET_FEED_TIMEOUT", "120"))
# Группы рынков Melbet, закреплённые вручную: «семейство=группа» через
# запятую, например «total=17,hcap=2,itotal1=15,bothscore=19». Обычно не
# нужно — парсер выбирает группу сам по всей линии. Пригодится, если
# выбор промахнулся: какие группы есть и что выбрано, показывает
# venv/bin/python -m app.diagnose_melbet.
MELBET_GROUPS = {}
for _pair in os.getenv("MELBET_GROUPS", "").split(","):
    if "=" in _pair:
        _family, _, _group = _pair.partition("=")
        if _group.strip().lstrip("gG").isdigit():
            MELBET_GROUPS[_family.strip()] = int(_group.strip().lstrip("gG"))
# Минимальная пауза между обходами Melbet, сек. Полная роспись — это
# запрос на КАЖДОЕ событие линии, и гонять её чаще нет смысла: прематч за
# минуту почти не двигается, а частый обход быстрее приводит к блокировке.
MELBET_MIN_REFRESH = float(os.getenv("MELBET_MIN_REFRESH", "60"))
# Включена ли Melbet. Фид отвечает только российским адресам (с чужого IP
# приходит 406 или страница «отключите VPN»), поэтому на зарубежном
# сервере её лучше выключить, чтобы не тратить обходы впустую.
MELBET_ENABLED = os.getenv("MELBET_ENABLED", "1") not in (
    "0", "false", "no", "")

# Список БК, которыми ограничен обход: «BOOKMAKERS=Winline,Fonbet,BetBoom».
# Пусто — работают все включённые. Меньше БК означает и меньше вилок (вилка
# живёт МЕЖДУ БК, и пар растёт квадратично), зато обход быстрее и кэфы
# свежее. Имена сверяются без учёта регистра и пробелов.
BOOKMAKERS_ONLY = tuple(
    b.strip().lower() for b in os.getenv("BOOKMAKERS", "").split(",")
    if b.strip())

# ---- Лайв-режим (матчи в игре) ----
# Лайв сканируется ОТДЕЛЬНЫМ быстрым циклом: коэффициенты в игре меняются
# ежесекундно, поэтому опрос чаще и котировки живут недолго.
# Акцент сканера — ПРЕМАТЧ: лайв можно полностью выключить, тогда ресурсы
# CPU/сети целиком уходят прематчу (полезно на слабом VPS). Переменная
# задаёт значение ПО УМОЛЧАНИЮ: дальше флаг переключается на ходу из
# админки (переключатель «Лайв-сканер») и сохраняется в базе — сохранённое
# значение имеет приоритет над переменной окружения при следующем запуске.
LIVE_ENABLED = os.getenv("LIVE_ENABLED", "1") not in ("0", "false", "no")
LIVE_SCAN_INTERVAL = float(os.getenv("LIVE_SCAN_INTERVAL", "12"))
# TTL лайв-котировок: если БК не обновляла их дольше — считаем протухшими
