LIVE_ODDS_TTL = float(os.getenv("LIVE_ODDS_TTL", "45"))
# Пауза между СОБСТВЕННЫМИ обновлениями одной БК в лайве. Каждая БК в лайве
# обновляется в своём потоке и как можно чаще (быстрая БК не ждёт медленную);
