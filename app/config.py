# ---- Домен, HTTPS и защита соединения ----
# Домен сайта (например «arb.example.ru»). Задан — сервер принимает
# запросы ТОЛЬКО с этим заголовком Host: чужой домен, направленный на ваш
# IP, дальше шлюза не пройдёт, и по нему нельзя ни собрать сессию, ни
