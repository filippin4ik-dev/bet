# следующей попыткой: долбить её прежним темпом бессмысленно и вредно —
# защита БК от этого только злее (проверено на Betcity: после двух часов
# частых запросов всей линии её сервер начал рвать соединения с IP вообще
# на все запросы), а котировки всё равно живут до ODDS_TTL. Потолок заметно
