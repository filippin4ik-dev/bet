# Сканер работает только с реальными данными БК (Winline / BetBoom / Fonbet /
# Liga Stavok) и только с ПРЕМАТЧЕМ — live-ставки отключены.
SCANNER_MODE = "prematch"

# Как часто обновлять прематч-котировки ОДНОЙ БК, сек. Каждая БК крутится
# в своём потоке и не ждёт остальных, поэтому это именно период обхода
# конкретной БК, а не общего круга: быстрая БК (Fonbet — полминуты)
# обновляется раз в SCAN_INTERVAL, медленная (Winline/BetBoom — минуты) —
# сразу после того, как закончила предыдущий обход. Больше значение —
# реже запросы и меньше трафика, но и кэфы в интерфейсе старше.
