TRUSTED_HOSTS = tuple(
    h.strip().lower() for h in os.getenv("TRUSTED_HOSTS", "").split(",")
    if h.strip()) + ((SITE_DOMAIN, f"www.{SITE_DOMAIN}") if SITE_DOMAIN
                     else ())
# Отправлять сессионные cookie только по HTTPS. «auto» — по факту схемы
# запроса (см. security.cookie_secure): на сервере без сертификата флаг не
# ставится, иначе войти было бы невозможно. Домен с сертификатом получен —
# ставьте COOKIE_SECURE=1.
COOKIE_SECURE = os.getenv("COOKIE_SECURE", "auto").strip().lower()
# Отправлять ли HTTP-запросы на HTTPS. Обычно этим занимается nginx
