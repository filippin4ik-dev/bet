FUZZY_NAME_NEAR_MISS_MIN = float(os.getenv("FUZZY_NAME_NEAR_MISS_MIN", "0.6"))

# Сколько таких «почти совпадений» помнить за пересчёт и сколько пар из них
# реально проверять на вилку. Проверка каждой пары — отдельный маленький
# пересчёт (десятки котировок), поэтому число ограничено: разбирать руками
