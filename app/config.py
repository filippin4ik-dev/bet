# что она была, было неоткуда.
#
# Теперь такие пары проверяются отдельно: движок пробует склеить их
# ПРИНУДИТЕЛЬНО, и если вилка появляется — строка уходит на вкладку
# «Отсеянные» с обоими написаниями. Это не автосклейка: ставить по такой
