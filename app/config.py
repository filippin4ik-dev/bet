SITE_SESSION_TTL = float(os.getenv("SITE_SESSION_TTL", "2592000"))
# Определять IP клиента по X-Forwarded-For (сайт за nginx, см. deploy/
# nginx.conf). Заголовку верим только если запрос пришёл из локальной сети,
# то есть от своего же nginx, и берём ПОСЛЕДНИЙ адрес цепочки — его
# добавляет сам nginx. 0 — всегда брать адрес соединения.
SITE_TRUST_PROXY = os.getenv("SITE_TRUST_PROXY", "1") not in ("0", "false", "no")
# Защита от перебора пароля: не больше N неудачных попыток с одного IP за
# окно в SITE_LOGIN_FAIL_WINDOW секунд.
SITE_LOGIN_MAX_FAILS = int(os.getenv("SITE_LOGIN_MAX_FAILS", "10"))
SITE_LOGIN_FAIL_WINDOW = float(os.getenv("SITE_LOGIN_FAIL_WINDOW", "300"))
# Забаненные адреса и подсети (формат как у SITE_IP_WHITELIST). Начальное
# значение: дальше список правится в админке — кнопкой «Забанить IP» в
# разделе «Кто на сайте» или руками в разделе «Доступ к сайту».
SITE_IP_BLACKLIST = os.getenv("SITE_IP_BLACKLIST", "").strip()

# ---- Кто на сайте: устройства посетителей и бан по устройству ----
# Каждому браузеру выдаётся cookie с идентификатором устройства — по ней в
# админке видно, кто смотрит сайт, и по ней же устройство банится. IP для
# этого не годится: у телефона он меняется каждый день, а за домашним
# роутером все выглядят одинаково. 0 — не вести список и не выдавать cookie.
VISITORS_ENABLED = os.getenv("VISITORS_ENABLED", "1") not in (
    "0", "false", "no", "")
# Сколько живёт cookie устройства, сек (по умолчанию год: бан должен
# переживать и перезапуск сервера, и месяц без визитов).
VISITOR_COOKIE_TTL = float(os.getenv("VISITOR_COOKIE_TTL", "31536000"))
# Сколько секунд после последнего запроса устройство считается «сейчас на
# сайте». Открытая вкладка опрашивает сервер раз в 5 с, так что окна в
# полторы минуты хватает и при спящем телефоне.
VISITOR_ONLINE_WINDOW = float(os.getenv("VISITOR_ONLINE_WINDOW", "90"))
# Сколько устройств держать в списке (забаненные хранятся всегда, сверх
# этого числа). Список нужен «посмотреть, кто ходит», а не как архив.
VISITORS_MAX = int(os.getenv("VISITORS_MAX", "300"))
# Раз в сколько секунд сбрасывать накопленные посещения в базу. Чаще —
# лишние записи в SQLite на каждый опрос интерфейса; реже — после
# внезапного падения процесса потеряется хвост посещений (сами баны
# пишутся в базу сразу и от этого не зависят).
VISITORS_FLUSH_INTERVAL = float(os.getenv("VISITORS_FLUSH_INTERVAL", "30"))

# Раз в сколько секунд авто-обновлять баланс подключённых аккаунтов БК.
BALANCE_REFRESH_INTERVAL = float(os.getenv("BALANCE_REFRESH_INTERVAL", "300"))

# Авто-ставки на вилки (ОЧЕНЬ рискованная функция: букмекеры банят аккаунты
# за вилочников, а автоматизация браузера может ошибиться в выборе исхода
# или размере ставки). Выключено по умолчанию — включает оператор осознанно.
AUTOBET_ENABLED = os.getenv("AUTOBET_ENABLED", "0") not in ("0", "false", "no", "")
# Пока не выключен явно — авто-ставка выполняется В РЕЖИМЕ ИМИТАЦИИ (dry-run):
# бот проходит весь расчёт и «нажимает» кнопки в логике, но реального запроса
# на сайт БК на размещение ставки не делает. Реальные ставки — только когда
# AUTOBET_DRY_RUN=0 И AUTOBET_ENABLED=1 одновременно.
AUTOBET_DRY_RUN = os.getenv("AUTOBET_DRY_RUN", "1") not in ("0", "false", "no", "")
# Не превышать этот процент от баланса аккаунта одной ставкой (защита от
# ошибок в расчёте лимита при неточном балансе).
AUTOBET_MAX_BALANCE_FRACTION = float(
    os.getenv("AUTOBET_MAX_BALANCE_FRACTION", "0.9"))
# Верхний потолок одной ставки в рублях (доп. защита, даже если баланс больше).
AUTOBET_MAX_STAKE = float(os.getenv("AUTOBET_MAX_STAKE", "5000"))
# Показывать ли авто-ставку в интерфейсе. Функция целиком осталась на
# месте (ручка /api/autobet/place, коннекторы, журнал ставок, настройки),
# но по умолчанию её не видно НИКОМУ: кнопки в карточке вилки нет, разделов
# «Авто-ставки» и «Журнал ставок» в админке нет. Ставки сейчас делаются
# руками, а спрятанная кнопка «поставить за меня» рядом с реальными
# деньгами — лишний повод нажать не туда. AUTOBET_UI=1 возвращает всё как
# было.
AUTOBET_UI = os.getenv("AUTOBET_UI", "0") not in ("0", "false", "no", "")
