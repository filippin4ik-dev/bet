# ---- Единоборства: чем считается «раунд» при расчёте тотала ----
# Одинаковая на вид линия «Тотал 2.5» в MMA/боксе у разных БК считается по
# РАЗНЫМ правилам, и это не мелочь: BetBoom засчитывает раунд, только если
# с его начала прошло не меньше ПОЛОВИНЫ времени раунда, а Fonbet считает
# тотал раундов «просто тоталом» (раунд идёт в зачёт с момента начала).
# Бой, остановленный на первой минуте третьего раунда, у BetBoom — это 2
# раунда, у Fonbet — 3: ТБ 2.5 у одной БК и ТМ 2.5 у другой проигрывают
# ОБА. То есть «вилка» между такими БК — не гарантированная прибыль, а
# гарантированный минус.
#
# Здесь перечислены БК, чьё правило ОТЛИЧАЕТСЯ от обычного: сканер не
# сшивает рынки счёта раундов (тотал, фора, чет/нечет всего боя) между БК
# с разными правилами, а такие пары показывает на вкладке «Отсеянные» —
# их можно проверить руками. Формат: «БК=правило» через запятую, имя БК
# сверяется без учёта регистра. Одинаковое правило у двух БК означает
# «считают одинаково, сшивать можно».
