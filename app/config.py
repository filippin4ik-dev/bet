# Сокращённое имя команды — ОТДЕЛЬНЫЙ случай, побуквенным сходством он не
# ловится. «Сувон» и «Сувон Самсунг», «Аль-Иттихад» и «Аль-Иттихад Джидда»,
# «Мидлсбро» и «Мидлсбро ФК» — это одна команда, но difflib даёт им 0.55–0.7,
# то есть ниже FUZZY_NAME_SIM_THRESHOLD, и событие между БК не сшивалось.
# Такие пары показывались только на вкладке «Отсеянные» — то есть вилка по
