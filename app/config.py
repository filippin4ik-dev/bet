# Случайная задержка между запросами к ОДНОЙ БК, сек (защита от блокировок)
REQUEST_DELAY_MIN = float(os.getenv("REQUEST_DELAY_MIN", "2"))
REQUEST_DELAY_MAX = float(os.getenv("REQUEST_DELAY_MAX", "5"))

# Передышка между пересчётами вилок, сек. Пересчёт по всем БК (сотни тысяч
# котировок) занимает секунды и работает в один поток; котировки БК приходят
# чаще, чем он успевает, поэтому без паузы он шёл бы непрерывно и отбирал
# процессор у самих обходов БК. Больше значение — меньше нагрузка, но вилка
# появляется в интерфейсе позже.
ARB_RECALC_MIN_GAP = float(os.getenv("ARB_RECALC_MIN_GAP", "5"))

