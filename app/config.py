ARB_REJECTED_MAX = int(os.getenv("ARB_REJECTED_MAX", "400"))

# ---- Вилки, которые не дошли до списка из-за сопоставления событий ----
# Событие сшивается между БК по паре имён команд и времени старта. Оба
# признака иногда расходятся: «Кимчхон Санму»/«Кимчхон Сангму», «Аль-Иттихад
