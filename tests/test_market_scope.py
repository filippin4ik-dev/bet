"""Тесты канонизации предмета/периода рынка (html_utils.market_scope).

scope — это ключ, по которому рынки РАЗНЫХ БК признаются одним и тем же
рынком. Ошибка здесь стоит дорого в обе стороны: слишком широкий scope
склеивает разные рынки в ЛОЖНУЮ вилку (рынок тайма против рынка всего
матча), слишком узкий — теряет реальные вилки.
"""
from app.parsers.html_utils import market_scope as ms


# ---------- период матча: разные падежи и словесные порядковые ----------

def test_period_ordinal_cases():
    """«1-й», «1-м», «1-ом», «1-го» — один и тот же период.

    Предложный падеж («в 1-м периоде», так пишет Betcity) раньше периодом
    НЕ распознавался: scope выходил пустым, и рынок периода сшивался с
    рынком всего матча в ложную вилку."""
    assert ms("Тотал 1-й тайм") == "half1"
    assert ms("Гол в 1-ом тайме") == "half1"
    assert ms("Обе забьют в 1-м периоде") == "period1"
    assert ms("Тотал 1-го тайма") == "half1"


def test_period_word_ordinal():
    """Порядковое СЛОВОМ — тот же период, что цифрой."""
    assert ms("Обе забьют в первом тайме") == "half1"
    assert ms("Обе забьют во втором тайме") == "half2"
    assert ms("Тотал очков в четвертой четверти") == "quarter4"
    assert ms("Первый тайм. Тотал") == ms("1-й тайм. Тотал") == "half1"


def test_cardinal_number_is_not_a_period():
    """«пять сетов» — количество (тотал), а не «5-й сет»: количественные
    числительные не должны превращаться в номер периода."""
    assert ms("Тотал пять сетов") == "sets"
    assert ms("Тотал сетов") == "sets"


def test_main_market_has_empty_scope():
    assert ms("Фактический исход") == ""
    assert ms("Тотал") == ""
    assert ms("Азиатская фора") == ""
    assert ms("Обе забьют") == ""
    assert ms("Чет/Нечет тотала") == ""
    assert ms("Индивидуальный тотал") == ""


# ---------- предмет рынка ----------

def test_subject_tokens():
    assert ms("угловые. Тотал") == "corners"
    assert ms("желтые карточки. Фора") == "cards"
    assert ms("Офсайды. Тотал") == "offsides"


def test_volleyball_sets_named_partii():
    """«Партия» (волейбол, наст. теннис) — это сет: рынок «Фора по
    партиям» одной БК обязан сойтись с «Форой по сетам» другой."""
    assert ms("Фора по партиям") == ms("Фора по сетам") == "sets"
    assert ms("1-я партия. Тотал") == ms("1-й сет. Тотал") == "set1"


def test_service_words_do_not_leak_into_scope():
    """Слова вида рынка не должны становиться предметом: иначе такой рынок
    не сойдётся с тем же рынком другой БК."""
    assert ms("Доп. тоталы 1-й тайм") == "half1"
    assert ms("Инд. тотал 2-й тайм") == "half2"
    assert ms("Азиатский инд. тотал") == ""


# ---------- киберспорт: объекты карты против убийств чемпионов ----------

def test_map_objectives_are_not_champion_kills():
    """Дракон, барон, Рошан — отдельные рынки, хотя Winline подписывает их
    через то же слово («тотал убийств драконов»). Пока они схлопывались в
    kills, сканер показывал вилку на матче LCP: «фора убийств» BetBoom
    против «форы убийств дракона» Winline — ставка на ней проигрышная."""
    kills = ms("фора убийств")
    assert kills == "kills"
    for objective in ("тотал убийств драконов", "фора убийств барона",
                      "фора убийств рошана", "тотал уничтоженных "
                      "ингибиторов", "уничтожена башня",
                      "уничтожена казарма"):
        assert ms(objective) != kills, objective
    assert len({ms("тотал убийств драконов"), ms("фора убийств барона"),
                ms("фора убийств рошана")}) == 3


def test_named_objective_drops_the_generic_kills_token():
    """Одна БК пишет «убийств драконов», другая — просто «драконов»: это
    один рынок, и общий токен убийств не должен их разводить."""
    assert ms("тотал убийств драконов") == ms("тотал драконов") == "dragons"


def test_elemental_dragons_are_kept_apart():
    """«Элементальные драконы» (BetBoom) считаются без Элдера — сшивать их
    с «драконами вообще» нельзя."""
    assert ms("тотал элементальных драконов") != ms("тотал драконов")


def test_kills_after_a_minute_are_a_different_market():
    """«Фора убийств с 10 минут» — не фора убийств за весь матч."""
    assert ms("фора убийств с 10 минут") != ms("фора убийств")


def test_penalty_minutes_are_not_touched_by_the_minute_rule():
    """Хоккейные штрафные минуты — не «рынок с N-й минуты»."""
    assert ms("тотал штрафных минут") == ms("Тотал штрафных минут")
    assert ms("тотал штрафных минут") != ms("фора убийств с 10 минут")


def test_plain_esports_kills_still_match_between_bookmakers():
    """То, ради чего всё и затевалось, ломать нельзя: обычные убийства
    (в т.ч. с номером карты) по-прежнему сходятся."""
    assert ms("1 карта фора убийств на карте") == "kills+map1"
    assert ms("фора убийств") == ms("тотал убийств") == "kills"


def test_unknown_subject_keeps_own_token():
    """Незнакомый предмет НЕ сливается с основным рынком (иначе ложная
    вилка «экзотика против всего матча»), а получает свой токен."""
    scope = ms("Суммарный тотал минут, на которых забиты голы")
    assert scope and scope != ""
    assert scope != ms("Тотал")


def test_player_comparison_is_not_a_team_market():
    """«Фолы игрока (сравнение игроков)» (LeonBet) — рынок про ДВУХ
    ИГРОКОВ, а не про две команды.

    Собственного токена у него не было, и ключ выходил тот же, что у
    «кто из КОМАНД сделает больше фолов» (Fonbet, Betcity). Цены там
    расходятся втрое — на живой линии ничья стоила 3.34 против 12.0, — и
    движок исправно объявлял это вилкой в 15–22 %. Ставка по такой
    «вилке» проигрывает обеими ногами.
    """
    team = ms("Фолы. Фактический исход")
    player = ms("Фолы игрока (сравнение игроков)")
    assert team == "fouls"
    assert player != team
    assert "fouls" in player and "players" in player


def test_player_comparison_of_any_subject_stays_apart():
    for subject in ("Сейвы", "Удары", "Удары в створ", "Голевые передачи"):
        team = ms(f"Тотал {subject.lower()}")
        player = ms(f"{subject} игрока (сравнение игроков)")
        assert player != team, subject
    assert ms("Сравнение спортсменов") == "players"


def test_per_player_totals_keep_their_own_numbers():
    """Складка «сравнения» не должна съесть номер игрока: «тотал первого
    игрока» и «тотал второго» — разные рынки (теннис, LeonBet)."""
    assert ms("Тотал первого игрока") != ms("Тотал второго игрока")
