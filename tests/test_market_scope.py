"""Тесты канонизации предмета/периода рынка (html_utils.market_scope).

scope — это ключ, по которому рынки РАЗНЫХ БК признаются одним и тем же
рынком. Ошибка здесь стоит дорого в обе стороны: слишком широкий scope
склеивает разные рынки в ЛОЖНУЮ вилку (рынок тайма против рынка всего
матча), слишком узкий — теряет реальные вилки.
"""
from app.parsers.html_utils import market_scope as ms


# ---------- период матча: разные падежи и словесные порядковые ----------

def test_period_ordinal_cases():
    """«1-й», «1-м», «1-ом», «1-го» — один и тот же период.

    Предложный падеж («в 1-м периоде», так пишет Betcity) раньше периодом
    НЕ распознавался: scope выходил пустым, и рынок периода сшивался с
    рынком всего матча в ложную вилку."""
    assert ms("Тотал 1-й тайм") == "half1"
    assert ms("Гол в 1-ом тайме") == "half1"
    assert ms("Обе забьют в 1-м периоде") == "period1"
    assert ms("Тотал 1-го тайма") == "half1"


def test_period_word_ordinal():
    """Порядковое СЛОВОМ — тот же период, что цифрой."""
    assert ms("Обе забьют в первом тайме") == "half1"
    assert ms("Обе забьют во втором тайме") == "half2"
    assert ms("Тотал очков в четвертой четверти") == "quarter4"
    assert ms("Первый тайм. Тотал") == ms("1-й тайм. Тотал") == "half1"


def test_cardinal_number_is_not_a_period():
    """«пять сетов» — количество (тотал), а не «5-й сет»: количественные
    числительные не должны превращаться в номер периода."""
    assert ms("Тотал пять сетов") == "sets"
    assert ms("Тотал сетов") == "sets"


def test_main_market_has_empty_scope():
    assert ms("Фактический исход") == ""
    assert ms("Тотал") == ""
    assert ms("Азиатская фора") == ""
    assert ms("Обе забьют") == ""
    assert ms("Чет/Нечет тотала") == ""
    assert ms("Индивидуальный тотал") == ""


# ---------- предмет рынка ----------

def test_subject_tokens():
    assert ms("угловые. Тотал") == "corners"
    assert ms("желтые карточки. Фора") == "cards"
    assert ms("Офсайды. Тотал") == "offsides"


def test_volleyball_sets_named_partii():
    """«Партия» (волейбол, наст. теннис) — это сет: рынок «Фора по
    партиям» одной БК обязан сойтись с «Форой по сетам» другой."""
    assert ms("Фора по партиям") == ms("Фора по сетам") == "sets"
    assert ms("1-я партия. Тотал") == ms("1-й сет. Тотал") == "set1"


def test_service_words_do_not_leak_into_scope():
    """Слова вида рынка не должны становиться предметом: иначе такой рынок
    не сойдётся с тем же рынком другой БК."""
    assert ms("Доп. тоталы 1-й тайм") == "half1"
    assert ms("Инд. тотал 2-й тайм") == "half2"
    assert ms("Азиатский инд. тотал") == ""


def test_unknown_subject_keeps_own_token():
    """Незнакомый предмет НЕ сливается с основным рынком (иначе ложная
    вилка «экзотика против всего матча»), а получает свой токен."""
    scope = ms("Суммарный тотал минут, на которых забиты голы")
    assert scope and scope != ""
    assert scope != ms("Тотал")
